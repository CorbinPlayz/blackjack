import {normalizeTable as N, applyAction as A} from './w.mjs';
const t=N({}); const H={role:'host',ref:''}; const P=r=>({role:'player',ref:r});
const ok=(r,m)=>{ if(!r.ok) throw new Error(m+': '+r.error); };
const no=(r,m)=>{ if(r.ok) throw new Error('should fail: '+m); };
ok(A(t,P('AAAAAAAA'),{type:'seat',name:'A',buyin:10000}),'seatA');
ok(A(t,P('BBBBBBBB'),{type:'seat',name:'B',buyin:10000}),'seatB');
no(A(t,H,{type:'start'}),'start without bets');
ok(A(t,P('AAAAAAAA'),{type:'bet',pid:1,amount:2000}),'betA');
no(A(t,P('AAAAAAAA'),{type:'bet',pid:2,amount:2000}),'bet other');
no(A(t,P('AAAAAAAA'),{type:'bet',pid:1,amount:20000}),'over');
no(A(t,H,{type:'start'}),'B no bet');
ok(A(t,P('BBBBBBBB'),{type:'bet',pid:2,amount:1000}),'betB');
no(A(t,P('AAAAAAAA'),{type:'start'}),'player start');
ok(A(t,H,{type:'start'}),'start');
ok(A(t,P('AAAAAAAA'),{type:'double',pid:1}),'double');
no(A(t,P('AAAAAAAA'),{type:'double',pid:1}),'double twice');
ok(A(t,H,{type:'settle',pid:1,outcome:'win'}),'settleA'); // +4000
if(t.players[0].balance!==14000) throw new Error('bal '+t.players[0].balance);
ok(A(t,P('AAAAAAAA'),{type:'bet',pid:1,amount:100}),'A pre-bets next round');
no(A(t,H,{type:'start'}),'round in play');
ok(A(t,H,{type:'settle',pid:2,outcome:'loss'}),'settleB');
if(t.round.n!==2||t.round.phase!=='betting') throw new Error('round not advanced');
ok(A(t,P('AAAAAAAA'),{type:'trivia',pid:1}),'trivia');
no(A(t,P('AAAAAAAA'),{type:'trivia',pid:1}),'trivia twice');
ok(A(t,P('BBBBBBBB'),{type:'dealer_request'}),'req');
ok(A(t,H,{type:'dealer_accept'}),'accept');
if(t.dealer!=='BBBBBBBB') throw new Error('dealer');
no(A(t,P('BBBBBBBB'),{type:'bet',pid:2,amount:100}),'dealer bets');
ok(A(t,P('BBBBBBBB'),{type:'start'}),'dealer starts');
ok(A(t,P('AAAAAAAA'),{type:'vault_deposit',pid:1,amount:1}),'vault dep x');
